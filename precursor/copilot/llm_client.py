"""Offline AI Copilot querying local Ollama with strict JSON enforcement and deterministic fallback."""

import os
import re
import json
import requests
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field

from precursor.incidents.schema import Incident
from precursor.copilot.runbook_matcher import RunbookMatch
from precursor.copilot.claim_verifier import (
    NumericalClaimVerifier,
    ClaimVerification,
    AssumptionVerification,
    ClaimStatus,
    AssumptionStatus,
)

DEFAULT_OLLAMA_URL = os.environ.get("OLLAMA_URL", "http://localhost:11434")


class CopilotHypothesisItem(BaseModel):
    """Structured hypothesis generated by LLM."""
    id: str = Field(..., description="Hypothesis ID (e.g. H1, H2)")
    statement: str = Field(..., description="Plausible root cause (explicitly designated as hypothesis)")
    confidence: float = Field(0.8, description="Estimated confidence between 0.0 and 1.0")
    rationale: str = Field("", description="Evidence supporting this hypothesis")


class CopilotAssumptionItem(BaseModel):
    """Explicit operational assumption asserted by LLM."""
    id: str = Field(..., description="Assumption ID (e.g. A1, A2)")
    statement: str = Field(..., description="Underlying operational assumption")
    metric_id: Optional[str] = Field(None, description="Telemetry metric ID tied to assumption")
    operator: Optional[str] = Field(None, description="Comparison operator: '<', '<=', '>', '>=', '==', '!='")
    expected_value: Optional[float] = Field(None, description="Expected value for validation")


class CopilotNumericalClaimItem(BaseModel):
    """Explicit numerical assertion made by LLM."""
    metric_id: str = Field(..., description="Telemetry metric identifier")
    asserted_value: float = Field(..., description="Numerical value asserted")
    unit: str = Field("", description="Metric unit: ms, %, Mbps, drops")
    context: str = Field("", description="Context of the assertion")


class CopilotStrictJSON(BaseModel):
    """Enforced schema for LLM response."""
    summary: str = Field(..., description="Telemetry evidence summary")
    hypotheses: List[CopilotHypothesisItem] = Field(default_factory=list)
    assumptions: List[CopilotAssumptionItem] = Field(default_factory=list)
    numerical_claims: List[CopilotNumericalClaimItem] = Field(default_factory=list)
    diagnostic_commands: List[str] = Field(default_factory=list)
    verification_steps: List[str] = Field(default_factory=list)
    risks_and_rollback: List[str] = Field(default_factory=list)


class CopilotResponse(BaseModel):
    """Structured response from the PRECURSOR AI Copilot."""
    summary: str = Field(..., description="Telemetry evidence summary")
    hypotheses: List[str] = Field(default_factory=list, description="Possible causes (strings for backward compatibility)")
    structured_hypotheses: List[CopilotHypothesisItem] = Field(default_factory=list, description="Structured hypotheses objects")
    assumptions: List[AssumptionVerification] = Field(default_factory=list, description="Independently audited operational assumptions")
    diagnostic_commands: List[str] = Field(default_factory=list, description="Copyable bash diagnostic commands")
    verification_steps: List[str] = Field(default_factory=list, description="Expected observations and verification steps")
    risks_and_rollback: List[str] = Field(default_factory=list, description="Operational risks and rollback guidance")
    claims: List[ClaimVerification] = Field(default_factory=list, description="Independently verified numerical claims")
    raw_llm_output: str = Field(..., description="Raw output generated by Ollama or fallback engine")
    model_used: str = Field(default="offline_fallback", description="Ollama model name or 'offline_heuristic_fallback'")


class OllamaCopilot:
    """
    Offline Copilot that queries local Ollama models with strict JSON schema enforcement.
    Grounded strictly in telemetry, gate state, and bundled runbooks.
    Provides automated heuristic fallback if Ollama is unreachable.
    """

    def __init__(
        self,
        base_url: str = DEFAULT_OLLAMA_URL,
        preferred_model: str = "llama3.2:1b",
        timeout_seconds: float = 6.0,
    ):
        self.base_url = base_url.rstrip("/")
        self.preferred_model = preferred_model
        self.timeout_seconds = timeout_seconds
        self.verifier = NumericalClaimVerifier(tolerance=0.10)

    def _get_available_model(self) -> Optional[str]:
        """Detect any local models in Ollama, or return None if offline."""
        try:
            r = requests.get(f"{self.base_url}/api/tags", timeout=1.5)
            if r.status_code == 200:
                models = r.json().get("models", [])
                if models:
                    names = [m["name"] for m in models]
                    if self.preferred_model in names:
                        return self.preferred_model
                    return names[0]
        except Exception:
            pass
        return None

    def generate_instant_overview(
        self,
        incident: Incident,
        telemetry_snapshot: Dict[str, Optional[float]],
        runbook_matches: List[RunbookMatch],
    ) -> CopilotResponse:
        """
        Instant (<5ms) deterministic incident overview and grounded guidance.
        Produces complete structured JSON, verified numerical claims, and audited assumptions.
        """
        raw_text = self._generate_heuristic_fallback(incident, telemetry_snapshot, runbook_matches)
        try:
            parsed_strict = CopilotStrictJSON(**json.loads(raw_text))
        except Exception:
            parsed_strict = CopilotStrictJSON(
                summary=f"Incident detected on {incident.title}.",
                hypotheses=[
                    CopilotHypothesisItem(
                        id="H1",
                        statement="Upstream route congestion or link degradation (Hypothesis)",
                        confidence=0.85,
                        rationale="Telemetry deviation observed",
                    )
                ],
                assumptions=[],
                numerical_claims=[],
                diagnostic_commands=["ip -s link show dev eth0", "ping -c 5 1.1.1.1"],
                verification_steps=["Confirm packet loss drops below 1.0%"],
                risks_and_rollback=["Interface restart may drop in-flight streams"],
            )

        raw_claims_dict = [c.model_dump() for c in parsed_strict.numerical_claims]
        claims = self.verifier.verify_structured_claims(raw_claims_dict, telemetry_snapshot)

        regex_claims = self.verifier.verify_response(raw_text, telemetry_snapshot)
        seen_keys = {(c.metric_id, c.claimed_value) for c in claims}
        for rc in regex_claims:
            if (rc.metric_id, rc.claimed_value) not in seen_keys:
                claims.append(rc)
                seen_keys.add((rc.metric_id, rc.claimed_value))

        assumptions_dict = [a.model_dump() for a in parsed_strict.assumptions]
        assumptions_audited = self.verifier.verify_assumptions(assumptions_dict, telemetry_snapshot)

        hypotheses_strings = [
            f"{h.statement} (confidence: {int(h.confidence * 100)}%)" if h.confidence else h.statement
            for h in parsed_strict.hypotheses
        ]

        return CopilotResponse(
            summary=parsed_strict.summary,
            hypotheses=hypotheses_strings,
            structured_hypotheses=parsed_strict.hypotheses,
            assumptions=assumptions_audited,
            diagnostic_commands=parsed_strict.diagnostic_commands,
            verification_steps=parsed_strict.verification_steps,
            risks_and_rollback=parsed_strict.risks_and_rollback,
            claims=claims,
            raw_llm_output=raw_text,
            model_used="instant_heuristic_runbook",
        )

    def query_ollama(
        self,
        incident: Incident,
        telemetry_snapshot: Dict[str, Optional[float]],
        runbook_matches: List[RunbookMatch],
        timeout_seconds: Optional[float] = None,
    ) -> Optional[CopilotResponse]:
        """
        Query local Ollama asynchronously for deep LLM synthesis.
        Returns CopilotResponse if successful, or None on error/timeout.
        """
        model = self._get_available_model()
        if not model:
            return None

        matched_rb_text = "\n\n".join([m.content for m in runbook_matches]) if runbook_matches else "No matching runbook."
        telemetry_str = ", ".join([f"{k}: {v}" for k, v in telemetry_snapshot.items() if v is not None])
        t_limit = timeout_seconds or 60.0

        prompt = f"""You are PRECURSOR Network Copilot. A network incident has occurred.
Analyze the incident using ONLY the provided telemetry and runbook context.

Incident Details:
- Title: {incident.title}
- Active Fault: {incident.is_active_fault}
- Predicted Horizon: {incident.predicted_horizon_minutes} minutes
- Gate State: {incident.gate_state.value}
- Current Telemetry: {telemetry_str}

Runbook Context:
{matched_rb_text}

MANDATORY INSTRUCTIONS:
1. Respond with a single strictly valid JSON object. Do not include markdown code block syntax.
2. Ground your answer strictly in the telemetry numbers.
3. Formulate your assumptions in the 'assumptions' array with quantitative metric conditions where possible.
4. Output schema format:
{{
  "summary": "Brief summary citing current telemetry readings",
  "hypotheses": [
    {{"id": "H1", "statement": "Plausible cause labelled (Hypothesis)", "confidence": 0.85, "rationale": "Evidence from telemetry"}}
  ],
  "assumptions": [
    {{"id": "A1", "statement": "Physical link state remains active", "metric_id": "link_state", "operator": "==", "expected_value": 1.0}}
  ],
  "numerical_claims": [
    {{"metric_id": "latency_ms", "asserted_value": 92.5, "unit": "ms", "context": "Observed latency breach"}}
  ],
  "diagnostic_commands": ["ip -s link show dev eth0", "ping -c 5 1.1.1.1"],
  "verification_steps": ["Verify packet loss recovers below 1.0%"],
  "risks_and_rollback": ["Restarting interface interrupts in-flight connections"]
}}
"""
        try:
            payload = {
                "model": model,
                "prompt": prompt,
                "stream": False,
                "format": "json",
                "options": {"temperature": 0.2, "top_p": 0.9, "num_predict": 300},
            }
            resp = requests.post(f"{self.base_url}/api/generate", json=payload, timeout=t_limit)
            if resp.status_code != 200:
                return None
            raw_text = resp.json().get("response", "")
            parsed_dict = json.loads(raw_text)
            parsed_strict = CopilotStrictJSON(**parsed_dict)

            raw_claims_dict = [c.model_dump() for c in parsed_strict.numerical_claims]
            claims = self.verifier.verify_structured_claims(raw_claims_dict, telemetry_snapshot)

            regex_claims = self.verifier.verify_response(raw_text, telemetry_snapshot)
            seen_keys = {(c.metric_id, c.claimed_value) for c in claims}
            for rc in regex_claims:
                if (rc.metric_id, rc.claimed_value) not in seen_keys:
                    claims.append(rc)
                    seen_keys.add((rc.metric_id, rc.claimed_value))

            assumptions_dict = [a.model_dump() for a in parsed_strict.assumptions]
            assumptions_audited = self.verifier.verify_assumptions(assumptions_dict, telemetry_snapshot)

            hypotheses_strings = [
                f"{h.statement} (confidence: {int(h.confidence * 100)}%)" if h.confidence else h.statement
                for h in parsed_strict.hypotheses
            ]

            return CopilotResponse(
                summary=parsed_strict.summary,
                hypotheses=hypotheses_strings,
                structured_hypotheses=parsed_strict.hypotheses,
                assumptions=assumptions_audited,
                diagnostic_commands=parsed_strict.diagnostic_commands,
                verification_steps=parsed_strict.verification_steps,
                risks_and_rollback=parsed_strict.risks_and_rollback,
                claims=claims,
                raw_llm_output=raw_text,
                model_used=model,
            )
        except Exception:
            return None

    def explain_and_recommend(
        self,
        incident: Incident,
        telemetry_snapshot: Dict[str, Optional[float]],
        runbook_matches: List[RunbookMatch],
    ) -> CopilotResponse:
        """
        Generate grounded troubleshooting guidance enforcing strict JSON schema and dual auditing.
        Synchronous path returns sub-5ms instant heuristic overview.
        """
        return self.generate_instant_overview(incident, telemetry_snapshot, runbook_matches)

    def _generate_heuristic_fallback(
        self,
        incident: Incident,
        telemetry: Dict[str, Optional[float]],
        runbook_matches: List[RunbookMatch],
    ) -> str:
        """Deterministic runbook-grounded guidance producing strict JSON."""
        rb = runbook_matches[0] if runbook_matches else None

        # Extract commands from runbook if present
        cmds = ["ip -s link show dev eth0", "ping -c 5 1.1.1.1"]
        if rb:
            found_cmds = re.findall(r"```bash\n(.*?)\n```", rb.content, re.DOTALL)
            if found_cmds:
                cmds = [line.strip() for line in found_cmds[0].split("\n") if line.strip() and not line.startswith("#")]

        # Determine numerical claims directly from active telemetry
        claims = []
        if telemetry.get("latency_ms") is not None:
            claims.append({
                "metric_id": "latency_ms",
                "asserted_value": round(float(telemetry["latency_ms"]), 2),
                "unit": "ms",
                "context": f"Observed round-trip latency is {round(float(telemetry['latency_ms']), 2)}ms",
            })
        if telemetry.get("packet_loss_pct") is not None:
            claims.append({
                "metric_id": "packet_loss_pct",
                "asserted_value": round(float(telemetry["packet_loss_pct"]), 2),
                "unit": "%",
                "context": f"Active packet loss rate is {round(float(telemetry['packet_loss_pct']), 2)}%",
            })
        if telemetry.get("jitter_ms") is not None:
            claims.append({
                "metric_id": "jitter_ms",
                "asserted_value": round(float(telemetry["jitter_ms"]), 2),
                "unit": "ms",
                "context": f"Measured RTT jitter is {round(float(telemetry['jitter_ms']), 2)}ms",
            })

        # Operational assumptions grounded in telemetry invariants
        assumptions = [
            {
                "id": "A1",
                "statement": "Physical carrier link remains operational",
                "metric_id": "link_state",
                "operator": "==",
                "expected_value": 1.0,
            },
            {
                "id": "A2",
                "statement": "Packet loss rate remains bounded under nominal SLA threshold (5.0%)",
                "metric_id": "packet_loss_pct",
                "operator": "<=",
                "expected_value": 5.0,
            },
        ]

        hypotheses = [
            {
                "id": "H1",
                "statement": "Interface bufferbloat or upstream bottleneck (Hypothesis)",
                "confidence": 0.88,
                "rationale": "Sustained latency elevation coinciding with packet queuing",
            },
            {
                "id": "H2",
                "statement": "Optical transceiver degradation or physical frame errors (Hypothesis)",
                "confidence": 0.65,
                "rationale": "Intermittent frame drops and jitter instability",
            },
        ]

        data = {
            "summary": f"Incident {incident.id} detected on eth0 ({incident.title}). Gate state: {incident.gate_state.value}.",
            "hypotheses": hypotheses,
            "assumptions": assumptions,
            "numerical_claims": claims,
            "diagnostic_commands": cmds[:4],
            "verification_steps": [
                "Verify interface carrier state: cat /sys/class/net/eth0/carrier",
                "Verify latency stabilizes below 30.0ms",
                "Confirm packet drops drop to zero",
            ],
            "risks_and_rollback": [
                "Restarting interface or flushing qdisc will drop in-flight TCP streams",
                "Rollback: sudo ip link set dev eth0 up",
            ],
        }

        return json.dumps(data, indent=2)
